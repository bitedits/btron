static inline void draw_nyan_sprite(GDEV *dev, H dst_x, H dst_y, int frame_idx) {
    if (!dev || !dev->pixels) return;
    if (frame_idx < 0) frame_idx = 0;
    frame_idx = frame_idx % NYAN_FRAME_COUNT;

    const uint8_t *rle = g_nyan_frames[frame_idx];
    uint16_t spans = g_nyan_frame_spans[frame_idx];
    volatile COLOR *pix = (volatile COLOR*)dev->pixels;
    H dev_w = dev->width;

    H x = 0;
    H y = 0;
    for (uint16_t s = 0; s < spans; s++) {
        uint8_t count = rle[s * 2];
        uint8_t col_idx = rle[s * 2 + 1];
        COLOR c = (col_idx < 14) ? g_nyan_palette[col_idx] : 0;
        BOOL visible = ((c & 0xFF000000) != 0);
        /* The palette is in COLOR order; the canvas is not. One swap per span,
         * not per pixel -- and most of these palettes are strongly non-greyscale,
         * so a missed swap here is the yellow-stripe-becomes-cyan bug. */
        const COLOR fb = BTRON_PIXEL_FB(c);

        while (count--) {
            if (visible) {
                H px = dst_x + x;
                H py = dst_y + y;
                if (px >= dev->clip.left && px < dev->clip.right &&
                    py >= dev->clip.top && py < dev->clip.bottom) {
                    pix[py * dev_w + px] = fb;
                } 
            }
            if (++x >= NYAN_FRAME_W) {
                x = 0;
                y++;
            }
        }
    }
}

